"""Beacon Claim primitives (ms-55 e-1648).

The "走る側" core of ms-55 SPEC: how parallel agents share which piece
of work each one has taken, so two agents don't double-spend on the
same task and a session restart can recover "what was I in the middle
of?".

Three primitive kinds (SPEC §5):

  * **request**: "Will you take X?" Receiver must accept or decline
    (= 受諾必須). Used when one agent has identified work but needs
    another to do it (different cwd, different OS, different skill set).

  * **handoff**: "I was on X, you take it now." Receiver must accept or
    decline. Used when an agent is leaving / context-running-out and
    needs to transfer in-progress state.

  * **claim**: "I'm taking X." First-publisher-wins broadcast (= no
    receiver consent needed). Used as the default coordination mode —
    every agent broadcasts what they pick up; conflicts surface at
    `latest_claims_by_target` time.

Wire format (= what lands on the bus, channel = `claim-signal`):

  {
    "kind": "claim",                 # discriminator
    "claim_kind": "request" | "handoff" | "claim",
    "claim_id": "cl-1750000000-abc",  # generated by build_claim_payload
    "target": {                      # what's being claimed
      "kind": "ms" | "task" | "operation" | "trek" | "free",
      "id":   "ms-55" / "e-1646" / ...
    },
    "from_session_id": "sv-...",     # who is claiming / handing off / requesting
    "to_session_id":   "sv-..."      # required for request / handoff;
                                     # empty for claim (broadcast)
    "intent": "free text — what specifically about target",
    "expires_at": "2026-06-16T00:00:00Z",  # optional auto-expiry
    "issued_at":  "2026-06-15T00:00:00Z",
    "metadata":   { ... }            # optional structured detail
  }

  # Response (for request / handoff):
  {
    "kind": "claim_response",
    "claim_id": "cl-1750000000-abc",
    "decision": "accept" | "decline",
    "from_session_id": "sv-...",      # the responder
    "reason": "free text",
    "issued_at": "..."
  }

  # Release (= "I'm done with this claim, others can take it"):
  {
    "kind": "claim_release",
    "claim_id": "cl-1750000000-abc",
    "from_session_id": "sv-...",
    "outcome": "completed" | "abandoned",
    "reason": "free text",
    "issued_at": "..."
  }

Persistence:

  Local mode: .beacon/active_claims.json — a single JSON dict
  keyed by claim_id, mirroring what the server-side subcollection
  would look like. Atomic write via temp-file + rename.

  Cloud mode: an `active_claims/` subcollection on the project
  document is the intended layout (matches v2 schema patterns).
  This module currently writes local-only; the cloud path lives in
  a TODO at the bottom of the file.

The CLI in lib/commands.py wraps these helpers into:

  beacon claim request --target ms:ms-55 --to sv-... --intent "..."
  beacon claim handoff --target task:e-1646 --to sv-... --intent "..."
  beacon claim post    --target task:e-1646 --intent "..."
  beacon claim list   [--mine] [--target ms:ms-55] [--json]
  beacon claim release <claim_id> [--outcome completed|abandoned]
"""

from __future__ import annotations

import json
import os
import secrets
import tempfile
import time
from dataclasses import dataclass, field
from datetime import datetime, timezone
from typing import Optional


# ---------------------------------------------------------------------------
# Channel + payload constants
# ---------------------------------------------------------------------------

CLAIM_CHANNEL = "claim-signal"

PAYLOAD_KIND_CLAIM = "claim"
PAYLOAD_KIND_CLAIM_RESPONSE = "claim_response"
PAYLOAD_KIND_CLAIM_RELEASE = "claim_release"

CLAIM_KIND_REQUEST = "request"
CLAIM_KIND_HANDOFF = "handoff"
CLAIM_KIND_CLAIM = "claim"
_VALID_CLAIM_KINDS = frozenset({
    CLAIM_KIND_REQUEST, CLAIM_KIND_HANDOFF, CLAIM_KIND_CLAIM,
})

#: Target kinds for claims. Wider than stop's target kinds because a
#: claim can lock onto an Operation or a free-form scope ("I'm doing
#: the AWS investigation") that doesn't have a beacon entry yet.
TARGET_MS = "ms"
TARGET_TASK = "task"
TARGET_OPERATION = "operation"
TARGET_TREK = "trek"
TARGET_FREE = "free"
_VALID_TARGET_KINDS = frozenset({
    TARGET_MS, TARGET_TASK, TARGET_OPERATION, TARGET_TREK, TARGET_FREE,
})

RESPONSE_ACCEPT = "accept"
RESPONSE_DECLINE = "decline"
_VALID_RESPONSES = frozenset({RESPONSE_ACCEPT, RESPONSE_DECLINE})

OUTCOME_COMPLETED = "completed"
OUTCOME_ABANDONED = "abandoned"
_VALID_OUTCOMES = frozenset({OUTCOME_COMPLETED, OUTCOME_ABANDONED})


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------

def _utcnow_iso() -> str:
    return datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def mint_claim_id() -> str:
    """Stable, sortable, collision-resistant claim id.

    Format: cl-<unix ts>-<6 hex chars>. Sorting by id naturally orders
    by issue time which makes "who got there first" comparisons trivial.
    """
    return f"cl-{int(time.time())}-{secrets.token_hex(3)}"


# ---------------------------------------------------------------------------
# Builders
# ---------------------------------------------------------------------------

def build_claim_payload(
    *,
    claim_kind: str,
    from_session_id: str,
    target_kind: str,
    target_id: str,
    intent: str = "",
    to_session_id: str = "",
    expires_at: str = "",
    claim_id: Optional[str] = None,
    metadata: Optional[dict] = None,
    issued_at: Optional[str] = None,
) -> dict:
    """Build a validated claim payload.

    Request / handoff REQUIRE to_session_id (= specific recipient).
    Plain claim (= broadcast) MUST NOT set to_session_id.

    Returns a fresh dict with a `claim_id` minted if the caller didn't
    pass one. Mint-on-build means the sender can reference the id
    immediately (= print it to the user, persist locally before the
    bus call returns).
    """
    if claim_kind not in _VALID_CLAIM_KINDS:
        raise ValueError(
            f"claim_kind must be one of {sorted(_VALID_CLAIM_KINDS)}, "
            f"got {claim_kind!r}"
        )
    if not from_session_id:
        raise ValueError("from_session_id is required")
    if target_kind not in _VALID_TARGET_KINDS:
        raise ValueError(
            f"target_kind must be one of {sorted(_VALID_TARGET_KINDS)}, "
            f"got {target_kind!r}"
        )
    if not target_id:
        raise ValueError("target_id is required")
    if claim_kind in (CLAIM_KIND_REQUEST, CLAIM_KIND_HANDOFF):
        if not to_session_id:
            raise ValueError(
                f"claim_kind={claim_kind} requires to_session_id "
                "(use claim_kind=claim for broadcast)"
            )
    else:  # CLAIM_KIND_CLAIM
        if to_session_id:
            raise ValueError(
                "claim_kind=claim must not set to_session_id "
                "(use request/handoff for targeted claims)"
            )

    payload: dict = {
        "kind": PAYLOAD_KIND_CLAIM,
        "claim_kind": claim_kind,
        "claim_id": claim_id or mint_claim_id(),
        "target": {"kind": target_kind, "id": target_id},
        "from_session_id": from_session_id,
        "intent": intent or "",
        "issued_at": issued_at or _utcnow_iso(),
    }
    if to_session_id:
        payload["to_session_id"] = to_session_id
    if expires_at:
        payload["expires_at"] = expires_at
    if metadata is not None:
        if not isinstance(metadata, dict):
            raise ValueError("metadata must be a dict if provided")
        payload["metadata"] = metadata
    return payload


def build_response_payload(
    *,
    claim_id: str,
    decision: str,
    from_session_id: str,
    reason: str = "",
    issued_at: Optional[str] = None,
) -> dict:
    if not claim_id:
        raise ValueError("claim_id is required")
    if decision not in _VALID_RESPONSES:
        raise ValueError(
            f"decision must be one of {sorted(_VALID_RESPONSES)}, "
            f"got {decision!r}"
        )
    if not from_session_id:
        raise ValueError("from_session_id is required")
    return {
        "kind": PAYLOAD_KIND_CLAIM_RESPONSE,
        "claim_id": claim_id,
        "decision": decision,
        "from_session_id": from_session_id,
        "reason": reason or "",
        "issued_at": issued_at or _utcnow_iso(),
    }


def build_release_payload(
    *,
    claim_id: str,
    outcome: str,
    from_session_id: str,
    reason: str = "",
    issued_at: Optional[str] = None,
) -> dict:
    if not claim_id:
        raise ValueError("claim_id is required")
    if outcome not in _VALID_OUTCOMES:
        raise ValueError(
            f"outcome must be one of {sorted(_VALID_OUTCOMES)}, "
            f"got {outcome!r}"
        )
    if not from_session_id:
        raise ValueError("from_session_id is required")
    return {
        "kind": PAYLOAD_KIND_CLAIM_RELEASE,
        "claim_id": claim_id,
        "outcome": outcome,
        "from_session_id": from_session_id,
        "reason": reason or "",
        "issued_at": issued_at or _utcnow_iso(),
    }


